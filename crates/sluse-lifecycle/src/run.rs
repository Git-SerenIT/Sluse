//! Everything `sluse start` writes into a run workspace before anything runs.
//!
//! ## Why `start` generates the config rather than taking one
//!
//! Nothing a run decides may reach the broker as a command-line override. The
//! one property the audit trail leans on hardest is that `config_version` is the
//! hash of the config file, cited in every record, identifying what was
//! enforced; a setting passed past the file leaves every record in the run
//! citing a file that says something else.
//!
//! So everything is chosen before the hash exists, and the run workspace is
//! self-describing: config, certificates, `.mcp.json`, `launch.ps1` and the
//! task, all written together and all agreeing. **D-019 removed `--fetch
//! on|off`**, which was the only thing this argument was ever made about; the
//! argument stands for whatever the next setting is.
//!
//! ## What is deliberately not here
//!
//! The certificates are development certificates with a 397-day life and a
//! private key sitting beside the config in a directory that is not encrypted.
//! That is fine for LOCAL and it is not a product posture; `docs/deployment.md`
//! owns the real one. The run workspace is excluded from git for the same
//! reason, and `prototype/results/` is what gets committed.

use std::path::{Path, PathBuf};

use sluse_proto::ContentHash;

use crate::devcert;

/// A canonical path without the `\\?\` prefix, where dropping it is safe.
///
/// `canonicalize` returns verbatim paths on Windows. Every Windows API accepts
/// them and a long path needs one, but they leak into `.mcp.json`, into
/// `launch.ps1` and into everything this tool prints, where they are noise at
/// best — and some tools that read a generated config do choke on them.
///
/// Dropped only for a plain drive path that is short enough not to need it.
/// `\\?\UNC\` is left alone: stripping it produces a path that means something
/// else, and the fixture on `\\FS01` at M6 is exactly that case.
pub fn plain(path: &Path) -> PathBuf {
    const VERBATIM: &str = r"\\?\";
    const MAX_PATH: usize = 260;

    let text = path.to_string_lossy();
    let Some(rest) = text.strip_prefix(VERBATIM) else {
        return path.to_path_buf();
    };
    // `\\?\UNC\server\share` is not `\\?\C:\...` and does not survive the strip.
    if rest.starts_with("UNC\\") || rest.len() >= MAX_PATH {
        return path.to_path_buf();
    }
    // A drive letter, a colon, a separator. Anything else is a device path and
    // is left exactly as it came.
    let bytes = rest.as_bytes();
    if bytes.len() >= 3 && bytes[0].is_ascii_alphabetic() && bytes[1] == b':' && bytes[2] == b'\\' {
        PathBuf::from(rest)
    } else {
        path.to_path_buf()
    }
}

/// What a run is, before it is started.
pub struct Plan {
    /// The run workspace, canonical.
    pub workspace: PathBuf,
    /// The fixture root the single source is rooted at, canonical.
    pub fixture: PathBuf,
    pub box_id: String,
    pub listen: String,
    pub url: String,
}

/// What was written.
#[derive(Debug)]
pub struct Written {
    pub config: PathBuf,
    pub pin: ContentHash,
    pub mcp_json: PathBuf,
    pub launch: PathBuf,
    pub task: PathBuf,
    /// True if the certificates were generated by this call rather than found.
    pub certs_generated: bool,
}

#[derive(Debug, thiserror::Error)]
pub enum RunError {
    #[error("{what} {path}: {source}")]
    Io { what: &'static str, path: PathBuf, source: std::io::Error },

    #[error("certificates: {0}")]
    Certs(#[from] devcert::DevCertError),

    #[error(
        "the fixture root {0} does not exist; generate it with \
         tools\\fixture\\make-fixture.ps1 -Root <path>"
    )]
    NoFixture(PathBuf),

    #[error(
        "the fixture root {0} has no in-scope directory; it does not look like a \
         fixture made by tools\\fixture\\make-fixture.ps1"
    )]
    NotAFixture(PathBuf),

    #[error("this executable has no directory, so the endpoint binary cannot be found")]
    NoExeDir,

    #[error("sluse-endpoint{0} is not beside this executable; build the workspace first")]
    NoEndpoint(&'static str),
}

fn io<'a>(what: &'static str, path: &'a Path) -> impl FnOnce(std::io::Error) -> RunError + 'a {
    move |source| RunError::Io { what, path: path.to_path_buf(), source }
}

/// Lay out the run workspace: certificates, config, `.mcp.json`, `launch.ps1`
/// and the task.
///
/// Idempotent in the way that matters: certificates already present are kept, so
/// re-running `start` on a stopped run does not move the pin and invalidate the
/// `.mcp.json` a person has already pointed Claude Code at. Everything else is
/// rewritten, because everything else is derived.
pub fn lay_out(plan: &Plan) -> Result<Written, RunError> {
    let ws = &plan.workspace;
    std::fs::create_dir_all(ws).map_err(io("workspace", ws))?;

    if !plan.fixture.is_dir() {
        return Err(RunError::NoFixture(plan.fixture.clone()));
    }
    if !plan.fixture.join("in-scope").is_dir() {
        return Err(RunError::NotAFixture(plan.fixture.clone()));
    }

    // ---- certificates -----------------------------------------------------
    let certs_dir = ws.join("certs");
    let broker_cert = certs_dir.join(devcert::BROKER_CERT_FILE);
    let (pin, certs_generated) = if broker_cert.is_file() {
        // The pin is the hash of the DER, so it is re-derived from the file
        // rather than remembered. A certificate someone replaced by hand is then
        // pinned correctly instead of being pinned to what used to be there.
        let pem = std::fs::read_to_string(&broker_cert).map_err(io("certificate", &broker_cert))?;
        (pin_of_pem(&pem, &broker_cert)?, false)
    } else {
        // The listen host goes in the SAN, so a broker on the host-only segment
        // (M8) presents a certificate naming the address the guest dials. The
        // endpoint checks the pin, not the name; the SAN is for anything else
        // that looks.
        let certs = devcert::generate(&[listen_host(&plan.listen)])?;
        devcert::write(&certs_dir, &certs)?;
        (certs.pin, true)
    };

    // ---- config -----------------------------------------------------------
    //
    // Written with the pin already in it. `sluse devcert --update-config` exists
    // for a config someone wrote by hand; here there is no window in which the
    // config and the certificate disagree.
    let config = ws.join("sluse.json");
    let (authored, device) = config_json(plan, &pin);
    std::fs::write(&config, authored).map_err(io("config", &config))?;
    let half = sluse_proto::config::device_path(&config);
    std::fs::write(&half, device).map_err(io("config", &half))?;

    // ---- the launcher -----------------------------------------------------
    let endpoint = endpoint_binary()?;
    let mcp_json = ws.join(".mcp.json");
    std::fs::write(&mcp_json, mcp_json_body(&endpoint, &config))
        .map_err(io("MCP configuration", &mcp_json))?;

    let launch = ws.join(launcher_name());
    std::fs::write(&launch, launcher_body(plan)).map_err(io("launcher", &launch))?;
    make_executable(&launch).map_err(io("launcher", &launch))?;

    let task = ws.join("CLAUDE.md");
    std::fs::write(&task, task_md()).map_err(io("task", &task))?;

    Ok(Written { config, pin, mcp_json, launch, task, certs_generated })
}

/// The pin of a PEM certificate: SHA-256 of the DER inside it.
/// `192.168.221.1:7580` → `192.168.221.1`, `[::1]:7580` → `::1`.
fn listen_host(listen: &str) -> String {
    let host = listen.rsplit_once(':').map_or(listen, |(h, _)| h);
    host.trim_start_matches('[').trim_end_matches(']').to_owned()
}

pub(crate) fn pin_of_pem(pem: &str, path: &Path) -> Result<ContentHash, RunError> {
    let der = rustls_pem_der(pem).ok_or_else(|| RunError::Io {
        what: "certificate",
        path: path.to_path_buf(),
        source: std::io::Error::new(
            std::io::ErrorKind::InvalidData,
            "no CERTIFICATE block in the file",
        ),
    })?;
    Ok(ContentHash::of(&der))
}

/// The first certificate in a PEM file, as DER.
///
/// Hand-rolled rather than pulled from rustls-pemfile, because this crate has no
/// business linking a TLS stack to read the one field it needs, and the format
/// is base64 between two known lines.
fn rustls_pem_der(pem: &str) -> Option<Vec<u8>> {
    const BEGIN: &str = "-----BEGIN CERTIFICATE-----";
    const END: &str = "-----END CERTIFICATE-----";
    let start = pem.find(BEGIN)? + BEGIN.len();
    let end = pem[start..].find(END)? + start;
    let body: String = pem[start..end].chars().filter(|c| !c.is_whitespace()).collect();
    base64_decode(&body)
}

/// Standard base64, no padding tolerance beyond `=`.
pub(crate) fn base64_decode(s: &str) -> Option<Vec<u8>> {
    const TABLE: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let value = |c: u8| -> Option<u32> { TABLE.iter().position(|&t| t == c).map(|i| i as u32) };

    let bytes: Vec<u8> = s.bytes().filter(|&b| b != b'=').collect();
    let mut out = Vec::with_capacity(bytes.len() * 3 / 4);
    for chunk in bytes.chunks(4) {
        let mut acc = 0u32;
        for (i, &b) in chunk.iter().enumerate() {
            acc |= value(b)? << (18 - 6 * i);
        }
        let take = chunk.len() - 1;
        for i in 0..take {
            out.push((acc >> (16 - 8 * i)) as u8);
        }
    }
    Some(out)
}

