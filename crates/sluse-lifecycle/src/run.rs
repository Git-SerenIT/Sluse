/// A JSON string literal. Backslashes in Windows paths make this not optional.
fn json_string(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// The endpoint binary, beside this one.
///
/// Beside, rather than on `PATH`: a `sluse.exe` from a `cargo build` and a
/// `sluse-endpoint.exe` from an install would be two different builds speaking
/// one wire contract, and the version skew would show up as a puzzle rather than
/// as an error.
fn endpoint_binary() -> Result<PathBuf, RunError> {
    const EXE: &str = if cfg!(windows) { ".exe" } else { "" };
    let here = std::env::current_exe().map_err(|_| RunError::NoExeDir)?;
    let dir = here.parent().ok_or(RunError::NoExeDir)?;
    let candidate = dir.join(format!("sluse-endpoint{EXE}"));
    if candidate.is_file() {
        Ok(candidate)
    } else {
        Err(RunError::NoEndpoint(EXE))
    }
}

/// The box's bundle, which the package puts in `box\` beside `bin\`
/// (slice 3): the base's build carries it onto its seed disk.
pub fn box_bundle() -> Result<PathBuf, String> {
    let here = std::env::current_exe().map_err(|e| e.to_string())?;
    let bundle = here
        .parent()
        .and_then(Path::parent)
        .map(|root| root.join("box").join("sluse-box-linux.tar.gz"))
        .ok_or("no install directory above this binary")?;
    if bundle.is_file() {
        Ok(bundle)
    } else {
        Err(format!("{} is missing: the package has no box bundle", bundle.display()))
    }
}

/// The broker binary, beside this one. Same reasoning.
pub fn broker_binary() -> Result<PathBuf, RunError> {
    const EXE: &str = if cfg!(windows) { ".exe" } else { "" };
    let here = std::env::current_exe().map_err(|_| RunError::NoExeDir)?;
    let dir = here.parent().ok_or(RunError::NoExeDir)?;
    let candidate = dir.join(format!("sluse-broker{EXE}"));
    if candidate.is_file() {
        Ok(candidate)
    } else {
        Err(RunError::NoEndpoint(EXE))
    }
}

