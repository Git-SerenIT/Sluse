    #[test]
    fn the_generated_config_sets_a_byte_threshold_and_no_fetch_cap() {
        // D-016 as amended: the prototype's generated run watches bytes, so M6
        // measures volume with the control on; the product default stays absent
        // and `maxFetchBytes` is deliberately unset, because capping the fetch
        // costs the coverage the second scored run measured (D-019).
        let dir = tempfile::tempdir().unwrap();
        let (body, device) = config_json(&plan(dir.path(), dir.path()), &ContentHash::of(b"pin"));
        let v: serde_json::Value = serde_json::from_str(&body).expect("generated config is JSON");
        assert_eq!(v["volume"]["bytes"], 52_428_800);
        assert_eq!(v["volume"]["admissions"], 25);
        assert!(v.get("maxFetchBytes").is_none(), "a generated run does not cap fetch");

        // And it still loads, which is the only assertion that matters if the
        // schema and this string ever disagree.
        let path = dir.path().join("sluse.json");
        std::fs::write(&path, &body).unwrap();
        std::fs::write(sluse_proto::config::device_path(&path), &device).unwrap();
        let loaded = sluse_proto::config::load(&path).expect("the generated config loads");
        assert_eq!(loaded.config.volume.bytes, Some(52_428_800));
        assert_eq!(loaded.config.max_fetch_bytes, None);
    }

